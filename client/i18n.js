  function isSupported(language) {
    return SUPPORTED.includes(language);
  }

  function normalizeLanguage(value, fallback = DEFAULT_LANGUAGE) {
    if (typeof value !== 'string') return fallback;
    const trimmed = value.trim();
    if (isSupported(trimmed)) return trimmed;
    const lower = trimmed.toLowerCase();
    if (lower === 'zh' || lower.startsWith('zh-')) return 'zh-CN';
    if (lower === 'en' || lower.startsWith('en-')) return 'en';
    return fallback;
  }

  function interpolate(template, vars) {
    if (!vars) return template;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
    ));
  }

  function lookup(language, key) {
    const primary = catalogs[language];
    if (primary && Object.prototype.hasOwnProperty.call(primary, key)) return primary[key];
    const fallback = catalogs[DEFAULT_LANGUAGE];
    if (fallback && Object.prototype.hasOwnProperty.call(fallback, key)) return fallback[key];
    return key;
  }

  function createI18n(options = {}) {
    const storage = options.storage === undefined ? defaultStorage() : options.storage;
    const listeners = new Set();
    let language = resolveInitial(options, storage);

    function t(key, vars) {
      return interpolate(lookup(language, key), vars);
    }

    function setLanguage(next) {
      const resolved = normalizeLanguage(next, language);
      if (resolved === language) return language;
      language = resolved;
      persist(storage, language);
      for (const listener of [...listeners]) listener(language);
      return language;
    }

    function subscribe(listener) {
      if (typeof listener !== 'function') throw new TypeError('Subscriber must be a function');
      listeners.add(listener);
      return () => listeners.delete(listener);
    }

    return {
      t,
      setLanguage,
      subscribe,
      get language() { return language; },
      get supported() { return SUPPORTED; },
    };
  }

  function defaultStorage() {
    try { return globalThis.localStorage; } catch { return null; }
  }

  function persist(storage, language) {
    try { storage?.setItem(STORAGE_KEY, language); } catch { /* private mode */ }
  }

  function readStored(storage) {
    try { return storage?.getItem(STORAGE_KEY); } catch { return null; }
  }

  function resolveInitial(options, storage) {
    const fallback = normalizeLanguage(options.defaultLanguage, DEFAULT_LANGUAGE);
    if (options.language) return normalizeLanguage(options.language, fallback);
    const stored = normalizeLanguage(readStored(storage), '');
    if (stored) return stored;
    return fallback;
  }

  function missingKeys() {
    const zh = catalogs['zh-CN'];
    const en = catalogs.en;
    const zhKeys = Object.keys(zh);
    const enKeys = Object.keys(en);
    return {
      missingInEn: zhKeys.filter((key) => !Object.prototype.hasOwnProperty.call(en, key)),
      missingInZh: enKeys.filter((key) => !Object.prototype.hasOwnProperty.call(zh, key)),
    };
  }

  return {
    SUPPORTED,
    DEFAULT_LANGUAGE,
    STORAGE_KEY,
    catalogs,
    createI18n,
    normalizeLanguage,
    isSupported,
    missingKeys,
  };
